#!/usr/bin/env python3
"""Gate: our QSPI register view must be generated from the authority's struct.

Why this exists
----------------
The AP image cannot include Armino's headers (`armino_baseline/.../hal` is only
on the CP include path), so `chips/bk7258/include/bk7258_qspi_hw.h` restates the
QSPI register block.  A restatement invites transcription errors and silent
drift, so it is not written by hand: it is GENERATED from
`armino_baseline/cp/middleware/soc/bk7258/soc/qspi_struct.h` for the registers
this driver actually touches, and this gate regenerates it and compares.

  --emit   write chips/bk7258/include/bk7258_qspi_hw.h
  (default) regenerate in memory and fail if the file on disk differs

The register whitelist is explicit: adding a register is a one-line change here,
so "what we depend on" is readable in one place and cannot grow unnoticed.

Second output: a coverage table mapping every operation the driver performs to
the authority helper that performs it, so an operation with no counterpart is a
gate failure rather than a surprise on the board.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
AUTHORITY = (ROOT / "chips/bk7258/armino_baseline/cp/middleware/soc/bk7258/soc"
             / "qspi_struct.h")
OUT_HEADER = ROOT / "chips/bk7258/include/bk7258_qspi_hw.h"

# Registers the LCD path uses.  Everything else in the block is deliberately
# absent: this driver is a panel transport, not a flash/PSRAM controller.
REGISTERS = {
    0x00: "dev_id",        # panel ID register
    0x01: "version_id",
    0x02: "glb_ctrl",      # soft_reset
    0x03: "core_status",
    0x08: "cmd_a_l",       # command bytes 5..8
    0x09: "cmd_a_h",       # command bytes 1..4
    0x0A: "cmd_a_cfg1",    # per-byte line mode
    0x0B: "cmd_a_cfg2",    # data line mode / dummy / mode
    0x10: "cmd_c_l",       # command bytes 5..8 (indirect channel)
    0x11: "cmd_c_h",       # command bytes 1..4 (the opcode)
    0x12: "cmd_c_cfg1",    # per-byte line mode
    0x13: "cmd_c_cfg2",    # cmd_start + data_len + data line mode
    0x18: "config",        # qspi_en / clk_rate / cpol / cpha
    0x19: "rst_cfg",       # sw_rst_fifo
    0x1A: "int_en",
    0x1B: "status_clr",    # W1C done flags
    0x1C: "status",        # cmd_start_done / tx_busy / fifo_empty
}

# Field name -> (register, lsb, width) for the plain (non-union) registers we
# use.  These carry no fields, so they are reproduced as raw words.
PLAIN = ("dev_id", "version_id", "core_status")

FIELD_RE = re.compile(
    r"uint32_t\s+([a-z_0-9]+)\s*:\s*(\d+)\s*;\s*/\*\*<\s*bit\[\s*(\d+)\s*"
    r"(?::\s*(\d+)\s*)?\]")

REG_COMMENT = re.compile(r"/\*\s*REG_0x([0-9A-Fa-f]+)\s*\*/")
UNION_CLOSE = re.compile(r"\}\s*[a-z_0-9]+\s*;")


def parse_authority(text: str):
    """{reg_index: [(field, lsb, width)]}, line-based state machine.

    The authority header writes the register index in a comment above each
    union/word ("/* REG_0x8 */", "/*REG_0x02*/", "/* REG_0x4 ~ REG_0x7 */"), so
    the index is tracked line by line rather than by regex over the whole file.
    A range comment ("~") closes the current register instead of opening one.
    """
    regs = {}
    current = None

    for line in text.splitlines():
        comment = REG_COMMENT.search(line)
        if comment:
            if "~" in comment.group(0):
                current = None
            else:
                current = int(comment.group(1), 16)
                regs.setdefault(current, [])
            continue

        if UNION_CLOSE.search(line):
            current = None
            continue

        field = FIELD_RE.search(line)
        if field and current is not None:
            name, _w, lsb, msb = field.groups()
            msb = msb if msb is not None else lsb
            regs[current].append((name, int(lsb), int(msb) - int(lsb) + 1))

    return {index: fields for index, fields in regs.items() if fields}


def build_header(regs) -> str:
    lines = [
        "/****************************************************************************",
        " * chips/bk7258/include/bk7258_qspi_hw.h",
        " *",
        " * GENERATED by chips/bk7258/tools/qspi_register_gate.py -- do not edit.",
        " * Source of record: armino_baseline/cp/middleware/soc/bk7258/soc/qspi_struct.h",
        " *",
        " * Only the registers the LCD transport uses are reproduced; each one keeps",
        " * the authority's field names, bit positions and widths verbatim, and the",
        " * gate fails if they ever diverge.",
        " ****************************************************************************/",
        "",
        "#ifndef __VENDOR_BEKEN_CHIP_BK7258_QSPI_HW_H",
        "#define __VENDOR_BEKEN_CHIP_BK7258_QSPI_HW_H",
        "",
        "#include <stdint.h>",
        '',
        '#include "include/bk7258_memorymap.h"',
        "",
        "#define BK7258_QSPI1_REG_BASE   UINT32_C(0x46060000)",
        "#define BK7258_QSPI1_DATA_BASE  UINT32_C(0x68000000)",
        "#define BK7258_QSPI_FIFO_WORDS  61",
        "#define BK7258_QSPI_FIFO_BASE   (BK7258_QSPI1_REG_BASE + UINT32_C(0x100))",
        "",
        "/* Field accessors: shift/mask per authority field. */",
        "",
    ]

    for index in sorted(regs):
        if index not in REGISTERS:
            continue
        fields = regs[index]
        lines.append(f"/* REG_0x{index:02X}  {REGISTERS[index]} */")
        for name, lsb, width in fields:
            mask = ((1 << width) - 1) << lsb
            base = f"BK7258_QSPI_{REGISTERS[index].upper()}_{name.upper()}"
            lines.append(f"#define {base}_LSB   {lsb:2d}")
            lines.append(f"#define {base}_WIDTH {width:3d}")
            lines.append(f"#define {base}_MASK  0x{mask:08X}u")
        lines.append("")

    lines += [
        "/* Offsets are word indices, as in the authority struct. */",
    ]
    for index in sorted(REGISTERS):
        lines.append(f"#define BK7258_QSPI_{REGISTERS[index].upper():<12} "
                     f"(BK7258_QSPI1_REG_BASE + UINT32_C(0x{index * 4:02X}))")

    lines += ["", "#endif /* __VENDOR_BEKEN_CHIP_BK7258_QSPI_HW_H */", ""]
    return "\n".join(lines)



# Operations the driver performs, and the authority helper each one mirrors.
# This is the coverage contract: every entry must exist in qspi_ll.h, so an
# operation we invent that the authority never performs shows up here first.
COVERAGE = (
    ("soft reset release", "qspi_ll_disable_soft_reset",
     "glb_ctrl.soft_reset = 0"),
    ("controller enable", "qspi_ll_enable", "config.qspi_en = 1"),
    ("clock divider", "qspi_ll_set_clk_div", "config.clk_rate"),
    ("indirect opcode", "qspi_ll_set_cmd_c_l", "cmd_c_l"),
    ("indirect opcode bytes", "qspi_ll_set_cmd_c_h", "cmd_c_h.cmd1"),
    ("indirect line modes", "qspi_ll_set_cmd_c_cfg1", "cmd_c_cfg1"),
    ("indirect data line", "qspi_ll_set_cmd_c_data_line", "cmd_c_cfg2.data_line"),
    ("indirect data length", "qspi_ll_set_cmd_c_data_length", "cmd_c_cfg2.data_len"),
    ("command start", "qspi_ll_cmd_c_start", "cmd_c_cfg2.cmd_start"),
    ("wait command done", "qspi_ll_wait_cmd_done", "status.cmd_start_done + status_clr"),
    ("payload out", "qspi_ll_io_write", "fifo_data[0..60]"),
    ("pixel stream out", "qspi_ll_io_write", "fifo_data, <=248 B per frame"),
)


def check_coverage() -> int:
    """Every mirrored helper must exist in the authority header."""
    ll = AUTHORITY.parents[1] / "hal/qspi_ll.h"   # soc/bk7258/hal/qspi_ll.h
    text = ll.read_text() if ll.exists() else ""
    missing = [h for _op, h, _field in COVERAGE if h not in text]

    width_op = max(len(op) for op, _h, _f in COVERAGE)
    width_fn = max(len(h) for _op, h, _f in COVERAGE)
    print("coverage: operation -> authority helper -> register field")
    for op, helper, field in COVERAGE:
        mark = "ok " if helper not in missing else "GAP"
        print(f"  [{mark}] {op:<{width_op}}  {helper:<{width_fn}}  {field}")

    if missing:
        print("coverage gate: %d operations have no authority counterpart: %s"
              % (len(missing), ", ".join(missing)), file=sys.stderr)
        return 1
    print("coverage gate: pass (%d operations mirrored)" % len(COVERAGE))
    return 0


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--emit", action="store_true",
                    help="write %s" % OUT_HEADER)
    args = ap.parse_args()

    text = AUTHORITY.read_text()
    regs = parse_authority(text)
    if not regs:
        print("gate: could not parse %s -- parser is broken" % AUTHORITY,
              file=sys.stderr)
        return 2

    header = build_header(regs)

    if args.emit:
        OUT_HEADER.write_text(header)
        print("wrote %s" % OUT_HEADER)
        return 0

    if not OUT_HEADER.exists():
        print("gate: %s missing -- run with --emit" % OUT_HEADER, file=sys.stderr)
        return 1

    if OUT_HEADER.read_text() != header:
        print("gate: %s diverges from the authority struct -- run with --emit"
              % OUT_HEADER, file=sys.stderr)
        return 1

    print("qspi register gate: pass (%d registers declared)" %
          sum(1 for i in regs if i in REGISTERS))
    return check_coverage()


if __name__ == "__main__":
    raise SystemExit(main())
